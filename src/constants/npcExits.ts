import type { NPC, PersonalGoal, PlayerBackstory } from '../types/game'
import { NPC_DEFINITIONS } from './npcs'

/**
 * Final scenes shown in VictoryModal. Two layers:
 *  1. Per-NPC exit lines — what happened to each revealed NPC, gated by
 *     relationship level. Turns the modal from generic "you won" into
 *     a roll of actual people the player remembers.
 *  2. Goal closure — the dream/promise from the start gets resolved with
 *     a vivid scene, win or lose.
 */

export interface ExitLine {
  npcId: string
  text: string
}

export function buildNpcExitLines(npcs: NPC[]): ExitLine[] {
  const lines: ExitLine[] = []

  for (const def of NPC_DEFINITIONS) {
    const npc = npcs.find(n => n.id === def.id)
    if (!npc?.isRevealed) continue
    const text = pickExitLine(def.id, npc.relationshipLevel)
    if (text) lines.push({ npcId: def.id, text })
  }

  return lines
}

function pickExitLine(npcId: string, r: number): string | null {
  switch (npcId) {
    case 'katya':
      if (r >= 75) return 'Катя запустила свою бухгалтерскую студию через полгода после того разговора. На сайте — ваш отзыв. Раз в квартал отчёты делает за чашку кофе. Дружба плюс работа, и обе на месте.'
      if (r >= 45) return 'Катя осталась бухгалтером в своей конторе. Иногда списываетесь — на «как дела». Когда у вас квартальная — она помогает по-старой памяти за символическое.'
      return 'Катя перестала отвечать. Ей не хватило вашего «спасибо, но дальше я сам». Поняли это поздно.'

    case 'viktor':
      if (r >= 70) return 'Виктор открыл новую точку — другого профиля, в другом районе. Зашёл как-то поздравить с годовщиной. На прилавке у него — ваша визитка. У вас — его.'
      if (r >= 40) return 'Виктор закрылся весной. Зла не держит. Иногда встречаетесь у магазина «Магнит», коротко жмёте руки. Бывает.'
      if (r >= 15) return 'Виктор закрылся, и до конца года писал про вас в районных чатах что-нибудь обидное. Потом перестал. Видимо, уехал.'
      return 'Виктор выдержал. Ваш магазин закрыт. Иногда проходите мимо — у него нормально торгуется. Это не злит, это просто факт.'

    case 'denis':
      if (r >= 70) return 'Денис открыл сеть точек. Вы остались у себя, но раз в год он зовёт на стратегическую сессию — слушать новых людей и спорить с ними. Деньги вернули с процентом, дружбу — без.'
      if (r >= 40) return 'Денис уехал в Дубай. Раз в год пишет «привет, как ты», ты пишешь «привет, нормально». Такая теперь форма дружбы.'
      return 'Денис обиделся. Тогда, после долгой паузы, написал «понял». И всё. С тех пор — тишина.'

    case 'irina':
      if (r >= 75) return 'Мама приходит два раза в неделю — встаёт за прилавок, говорит с покупателями, рассказывает им байки про советский общепит. Покупатели оставляют ей конфеты — она передаёт детдому. Это её ритм.'
      if (r >= 50) return 'Мама звонит каждый вечер. Не лезет в дела, но помнит ваше расписание лучше вас. На день рождения испекла торт — настоящий, с орехами.'
      return 'Мама звонит редко. Когда говорит — короткие ответы. Год прошёл, а как будто два. Что-то надо чинить — но не знаете как.'

    case 'artem':
      if (r >= 75) return 'Артём — соучредитель. Его 10% видны на каждом отчёте. У него улыбка, которую вы не помнили со школы. Совладение работает.'
      if (r >= 50) return 'Артём остался ведущим сотрудником. Премии получает, рекламу делает, сделал систему учёта — всё ваше теперь на ней работает. Зарплата честная, отношения хорошие.'
      if (r >= 25) return 'Артём ушёл через полгода. Не громко, но окончательно. С новой работы прислал смс: «Спасибо за опыт». И, кажется, действительно спасибо.'
      return 'Артём ушёл с обидой. Старый коллега, теперь — никто. Иногда видите его в инстаграме — там у него своя жизнь, и вы в ней не упомянуты.'

    case 'mikhail':
      if (r >= 70) return 'Михаил пишет из Краснодара. Внуки, веранда, рыбалка по выходным. В декабре прислал ящик мандаринов — без повода, «просто чтоб не забывали».'
      if (r >= 40) return 'Михаил передал бизнес преемнику. Поставки идут, претензий нет. Поздравляет с новым годом смской — и это всё.'
      return 'Михаил исчез из эфира после того случая. Преемник формально вежлив, но вы оба понимаете — мостов больше нет.'

    case 'tamara':
      if (r >= 70) return 'Тамара звонит из деревни у дочери. Раз в месяц, всегда вечером в среду. Передаёт трубку Насте — та коротко: «здравствуй» — и убегает играть. Деревянный календарь с её ёлкой стоит у входа.'
      if (r >= 40) return 'Тамара переехала. Иногда дочка передаёт привет через знакомых. Календарь с Настиной ёлкой никому не отдали — пусть будет.'
      return 'Тамара переехала молча. Календарь забыли спросить, отдать ли. Так и стоит у входа — просто потому, что Настина ёлка нарисована криво и трогательно.'

    case 'gena':
      if (r >= 70) return 'Дядя Гена устроился-таки на нормальную работу — сторожем на парковку. Звонит реже, но если звонит — без схем. Обычные семейные новости.'
      if (r >= 40) return 'Дядя Гена раз в три месяца пробует новую тему. Раз в три месяца вы говорите «нет». Он не обижается. Этот ритуал — это и есть отношения.'
      return 'Дядя Гена пропал куда-то после той истории. Мама говорит — где-то в Подмосковье. Не звонит. Может, оно и к лучшему.'
  }
  return null
}

/**
 * Goal closure scene — what happened to the dream. Two outcomes per goal,
 * tinted by motivation backstory for extra texture.
 */
export interface GoalClosure {
  title: string
  text: string
}

export function buildGoalClosure(
  goal: PersonalGoal | null | undefined,
  backstory: PlayerBackstory | null,
  balance: number,
): GoalClosure | null {
  if (!goal) return null

  if (goal.achieved) {
    return achievedClosure(goal, backstory, balance)
  }
  if (goal.missed) {
    return missedClosure(goal, backstory)
  }
  return {
    title: 'Цель пока в работе',
    text: `«${goal.shortLabel}» — ещё впереди. Вы остановились, не дойдя. Может, в следующий раз.`,
  }
}

