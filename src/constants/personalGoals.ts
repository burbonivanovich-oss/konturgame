import type { BackstoryPersonal, PersonalGoal } from '../types/game'

/**
 * Личные цели — то, ради чего вы не уходите обратно в найм.
 *
 * Переписаны после фидбэка, что прошлый сет (ремонт родителям /
 * депозит подруге / спасти сквер) воспринимался как «героические
 * сюжеты». Новый сет грубее и ближе к жизни:
 *   • free      — закрыть кредитку (личное освобождение от прошлого)
 *   • friend    — оплатить брату первый курс института (близкие)
 *   • hometown  — выкупить помещение (предпринимательский суверенитет)
 *
 * Один личный мотив, один семейный, один стратегический —
 * каждый ставит игрока в разное отношение с деньгами.
 */
export const PERSONAL_GOAL_TEMPLATES: Record<BackstoryPersonal, Omit<PersonalGoal, 'achieved' | 'missed'>> = {
  free: {
    id: 'close_debt',
    shortLabel: 'Закрыть кредитку',
    description:
      'Кредитка тянется с 2022-го. Лимит 350 000, минимальный платёж уходит в проценты, тело долга не уменьшается. Хотите закрыть её до Нового года — чтобы в январе впервые за три года открыть приложение банка без неприятного укола. Срок — неделя 36.',
    targetAmount: 350_000,
    deadlineWeek: 36,
  },
  friend: {
    id: 'brother_tuition',
    shortLabel: 'Брату на учёбу',
    description:
      'Брат поступил в институт — на бюджет не дотянул три балла, прошёл на платный. Родители не вытянут: мамина зарплата в школе и папина пенсия. Договорились — первый курс закрываете вы, дальше он сам. Два семестра — 320 000 ₽, к началу учебного года, неделя 32.',
    targetAmount: 320_000,
    deadlineWeek: 32,
  },
  hometown: {
    id: 'buy_premises',
    shortLabel: 'Выкупить помещение',
    description:
      'Хозяин помещения — пенсионер, нервничает каждые полгода: «или плачу больше, или съезжаю». Через риелтора узнали — готов продать за 400 000 ₽, если внесёте до зимы. Не аренда — свой угол. Конец вечной нервотрёпки с продлениями. Срок — неделя 38.',
    targetAmount: 400_000,
    deadlineWeek: 38,
  },
}

export function createPersonalGoal(personal: BackstoryPersonal): PersonalGoal {
  const template = PERSONAL_GOAL_TEMPLATES[personal]
  return {
    ...template,
    achieved: false,
    missed: false,
  }
}
